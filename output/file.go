// FileStreamOutput represents a response that serves a file inline (for viewing in browser)
// Similar to Laravel's response()->file()
type FileStreamOutput struct {
	filePath    string
	fileName    string
	content     []byte
	code        int
	headers     map[string]string
	contentType string
	isInline    bool
	eTag        string
	lastMod     time.Time
	cacheMaxAge int // seconds, 0 = no cache
}

// FileOutputOption configures a FileStreamOutput
type FileOutputOption func(*FileStreamOutput)

// WithFileHeaders adds custom headers
func WithFileHeaders(headers map[string]string) FileOutputOption {
	return func(f *FileStreamOutput) {
		for k, v := range headers {
			f.headers[k] = v
		}
	}
}

// WithFileContentType overrides auto-detected content type
func WithFileContentType(contentType string) FileOutputOption {
	return func(f *FileStreamOutput) {
		f.contentType = contentType
	}
}

// WithCache sets cache headers (max-age in seconds)
func WithCache(maxAge int) FileOutputOption {
	return func(f *FileStreamOutput) {
		f.cacheMaxAge = maxAge
	}
}

// WithETag sets a custom ETag
func WithETag(eTag string) FileOutputOption {
	return func(f *FileStreamOutput) {
		f.eTag = eTag
	}
}

// WithLastModified sets the Last-Modified header
func WithLastModified(t time.Time) FileOutputOption {
	return func(f *FileStreamOutput) {
		f.lastMod = t
	}
}

// WithFileName sets a custom display name
func WithFileName(name string) FileOutputOption {
	return func(f *FileStreamOutput) {
		f.fileName = name
	}
}

// File serves a file for inline viewing (e.g., images, PDFs in browser)
// Similar to Laravel's response()->file()
func File(path string, opts ...FileOutputOption) *FileStreamOutput {
	contentType := detectMimeType(path)
	fileName := filepath.Base(path)

	f := &FileStreamOutput{
		filePath:    path,
		fileName:    fileName,
		content:     nil,
		code:        http.StatusOK,
		headers:     make(map[string]string),
		contentType: contentType,
		isInline:    true,
		cacheMaxAge: 0,
	}

	for _, opt := range opts {
		opt(f)
	}

	return f
}

