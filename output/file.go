// DeleteFileAfterSend marks the file for deletion after sending
// Note: Actual deletion should be handled by the response writer
func (f *FileStreamOutput) DeleteFileAfterSend() *FileStreamOutput {
	f.headers["X-Delete-After-Send"] = "true"
	return f
}

// detectMimeType detects MIME type from file path
func detectMimeType(path string) string {
	// Try to detect from extension first
	ext := filepath.Ext(path)
	if mimeType := mime.TypeByExtension(ext); mimeType != "" {
		return mimeType
	}

	// Fallback: try to read file and detect
	file, err := os.Open(path)
	if err != nil {
		return "application/octet-stream"
	}
	defer file.Close()

	// Read first 512 bytes for detection
	buffer := make([]byte, 512)
	n, err := file.Read(buffer)
	if err != nil {
		return "application/octet-stream"
	}

	return http.DetectContentType(buffer[:n])
}

// detectMimeTypeFromFilename detects MIME type from filename
func detectMimeTypeFromFilename(filename string) string {
	ext := filepath.Ext(filename)
	if mimeType := mime.TypeByExtension(ext); mimeType != "" {
		return mimeType
	}
	return "application/octet-stream"
}

