// StreamDownload creates a download from a streaming callback
// Similar to Laravel's response()->streamDownload()
type StreamDownloadOutput struct {
	fileName    string
	callback    func(writer func([]byte) error) error
	code        int
	headers     map[string]string
	contentType string
}

// StreamDownload serves content generated by a callback as a download
// Useful for generating large files on-the-fly (e.g., CSV exports)
func StreamDownload(filename string, callback func(writer func([]byte) error) error, opts ...FileOutputOption) *StreamDownloadOutput {
	contentType := detectMimeTypeFromFilename(filename)

	s := &StreamDownloadOutput{
		fileName:    filename,
		callback:    callback,
		code:        http.StatusOK,
		headers:     make(map[string]string),
		contentType: contentType,
	}

	// Apply opts that are compatible
	tempFile := &FileStreamOutput{headers: s.headers, contentType: s.contentType}
	for _, opt := range opts {
		opt(tempFile)
	}
	s.headers = tempFile.headers
	s.contentType = tempFile.contentType

	return s
}

// Data returns nil as streaming is handled separately
func (s *StreamDownloadOutput) Data() any {
	return nil
}

// Code returns the HTTP status code
func (s *StreamDownloadOutput) Code() int {
	return s.code
}

// Headers returns the headers including Content-Disposition
func (s *StreamDownloadOutput) Headers() map[string]string {
	headers := make(map[string]string)
	for k, v := range s.headers {
		headers[k] = v
	}
	headers["Content-Disposition"] = fmt.Sprintf(`attachment; filename="%s"`, s.fileName)
	headers["Content-Type"] = s.contentType
	return headers
}

// ContentType returns the content type
func (s *StreamDownloadOutput) ContentType() string {
	return s.contentType
}

// StreamCallback returns the streaming callback
func (s *StreamDownloadOutput) StreamCallback() func(writer func([]byte) error) error {
	return s.callback
}

// FilePath returns empty (not a file-based output)
func (s *StreamDownloadOutput) FilePath() string {
	return ""
}

// FileName returns the download filename
func (s *StreamDownloadOutput) FileName() string {
	return s.fileName
}

// IsInline returns false (always a download)
func (s *StreamDownloadOutput) IsInline() bool {
	return false
}

// Data returns the file content or reads from path
func (f *FileStreamOutput) Data() any {
	if f.content != nil {
		return f.content
	}

	// Read file content
	file, err := os.Open(f.filePath)
	if err != nil {
		return []byte(fmt.Sprintf("Error opening file: %v", err))
	}
	defer file.Close()

	content, err := io.ReadAll(file)
	if err != nil {
		return []byte(fmt.Sprintf("Error reading file: %v", err))
	}

	return content
}

// Code returns the HTTP status code
func (f *FileStreamOutput) Code() int {
	return f.code
}

// Headers returns all headers including Content-Disposition
func (f *FileStreamOutput) Headers() map[string]string {
	headers := make(map[string]string)
	for k, v := range f.headers {
		headers[k] = v
	}

	// Set Content-Disposition
	if f.isInline {
		headers["Content-Disposition"] = fmt.Sprintf(`inline; filename="%s"`, f.fileName)
	} else {
		headers["Content-Disposition"] = fmt.Sprintf(`attachment; filename="%s"`, f.fileName)
	}

	// Set Content-Type
	headers["Content-Type"] = f.contentType

	// Set Content-Length if we have content
	if f.content != nil {
		headers["Content-Length"] = strconv.Itoa(len(f.content))
	} else if f.filePath != "" {
		if info, err := os.Stat(f.filePath); err == nil {
			headers["Content-Length"] = strconv.FormatInt(info.Size(), 10)
		}
	}

	// Set cache headers
	if f.cacheMaxAge > 0 {
		headers["Cache-Control"] = fmt.Sprintf("public, max-age=%d", f.cacheMaxAge)
	} else {
		headers["Cache-Control"] = "no-cache, no-store, must-revalidate"
		headers["Pragma"] = "no-cache"
		headers["Expires"] = "0"
	}

	// Set ETag if provided
	if f.eTag != "" {
		headers["ETag"] = f.eTag
	}

	// Set Last-Modified if provided
	if !f.lastMod.IsZero() {
		headers["Last-Modified"] = f.lastMod.UTC().Format(http.TimeFormat)
	}

	return headers
}

